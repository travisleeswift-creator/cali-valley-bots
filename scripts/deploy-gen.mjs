// Run after `npm run build`:  KV_ID=<kv namespace id> node scripts/deploy-gen.mjs
// Embeds dist/ into one Worker module that also serves the optional sync API
// (/api/sync/<64-hex id>, GET/PUT, stored in the SYNC KV namespace). Writes:
//   .deploy/worker.js            — the Worker source
//   .deploy/deploy-connector.js  — async function for the Cloudflare connector's execute tool
// (Static-asset uploads 401 through the connector, so files are embedded instead.)
import fs from "node:fs";
import path from "node:path";

const DIST = path.resolve("dist");
const OUT = path.resolve(".deploy");
const WORKER_NAME = "cali-valley-bots";
const COMPAT_DATE = "2026-10-01";
const KV_ID = process.env.KV_ID || "";
const MIME = { ".html": "text/html; charset=utf-8", ".js": "application/javascript; charset=utf-8", ".css": "text/css; charset=utf-8", ".json": "application/json; charset=utf-8", ".svg": "image/svg+xml", ".png": "image/png", ".ico": "image/x-icon", ".webmanifest": "application/manifest+json" };

if (!fs.existsSync(DIST)) { console.error("dist/ missing — run npm run build first"); process.exit(1); }
if (!KV_ID) { console.error("KV_ID env var required"); process.exit(1); }
const walk = d => fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
const files = {};
for (const f of walk(DIST)) {
  const rel = "/" + path.relative(DIST, f).split(path.sep).join("/");
  files[rel] = { b64: fs.readFileSync(f).toString("base64"), ct: MIME[path.extname(rel).toLowerCase()] || "application/octet-stream" };
}

const workerSource = `// Auto-generated by scripts/deploy-gen.mjs — do not edit.
const FILES = ${JSON.stringify(files)};
const HDRS = { "X-Content-Type-Options": "nosniff", "Referrer-Policy": "strict-origin-when-cross-origin", "X-Robots-Tag": "noindex, nofollow" };
const CORS = { "Access-Control-Allow-Origin": "*", "Access-Control-Allow-Methods": "GET, PUT, OPTIONS", "Access-Control-Allow-Headers": "Content-Type", "Access-Control-Max-Age": "86400" };
const MAX_SYNC_BYTES = 20 * 1024 * 1024;
const cache = new Map();
function bodyOf(p) {
  if (!cache.has(p)) { const bin = atob(FILES[p].b64); const u = new Uint8Array(bin.length); for (let i = 0; i < bin.length; i++) u[i] = bin.charCodeAt(i); cache.set(p, u); }
  return cache.get(p);
}
function json(obj, status) { return new Response(JSON.stringify(obj), { status, headers: { ...CORS, "content-type": "application/json", "cache-control": "no-store" } }); }
async function sync(request, env, id) {
  if (request.method === "OPTIONS") return new Response(null, { status: 204, headers: CORS });
  if (!/^[a-f0-9]{64}$/.test(id)) return json({ error: "bad id" }, 400);
  const key = "sync:" + id;
  if (request.method === "GET") {
    const v = await env.SYNC.get(key);
    if (v == null) return json({ error: "not found" }, 404);
    return new Response(v, { status: 200, headers: { ...CORS, "content-type": "application/json", "cache-control": "no-store" } });
  }
  if (request.method === "PUT") {
    const len = Number(request.headers.get("content-length") || 0);
    if (len > MAX_SYNC_BYTES) return json({ error: "too large" }, 413);
    const text = await request.text();
    if (text.length > MAX_SYNC_BYTES) return json({ error: "too large" }, 413);
    let o; try { o = JSON.parse(text); } catch (_) { return json({ error: "bad body" }, 400); }
    if (!o || !o.iv || !o.ct) return json({ error: "must be encrypted" }, 400);
    await env.SYNC.put(key, text);
    return json({ ok: true }, 200);
  }
  return json({ error: "method not allowed" }, 405);
}
export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    if (url.pathname.startsWith("/api/sync/")) return sync(request, env, url.pathname.slice(10));
    if (request.method !== "GET" && request.method !== "HEAD") return new Response("Method Not Allowed", { status: 405 });
    let p = url.pathname === "/" ? "/index.html" : url.pathname;
    if (!FILES[p]) p = "/index.html";
    const h = new Headers(HDRS);
    h.set("content-type", FILES[p].ct);
    h.set("cache-control", p.startsWith("/assets/") ? "public, max-age=31536000, immutable" : "no-cache");
    return new Response(request.method === "HEAD" ? null : bodyOf(p), { status: 200, headers: h });
  },
};
`;

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, "worker.js"), workerSource);
const connector = `async () => {
  const name = ${JSON.stringify(WORKER_NAME)};
  const meta = { main_module: "worker.js", compatibility_date: ${JSON.stringify(COMPAT_DATE)}, bindings: [{ type: "kv_namespace", name: "SYNC", namespace_id: ${JSON.stringify(KV_ID)} }] };
  const code = ${JSON.stringify(workerSource)};
  const form = new FormData();
  form.append("metadata", new Blob([JSON.stringify(meta)], { type: "application/json" }));
  form.append("worker.js", new Blob([code], { type: "application/javascript+module" }), "worker.js");
  const up = await cloudflare.request({ method: "PUT", path: \`/accounts/\${accountId}/workers/scripts/\${name}\`, body: form });
  const sd = await cloudflare.request({ method: "POST", path: \`/accounts/\${accountId}/workers/scripts/\${name}/subdomain\`, body: { enabled: true, previews_enabled: false } });
  return { uploaded: up.success, errors: up.errors, size: up.result && up.result.size, subdomain: sd.result, url: "https://" + name + ".travisleeswift.workers.dev" };
}`;
fs.writeFileSync(path.join(OUT, "deploy-connector.js"), connector);
console.log(JSON.stringify({ files: Object.keys(files), workerBytes: Buffer.byteLength(workerSource), connectorBytes: Buffer.byteLength(connector) }));
